import { test, expect } from "@playwright/test";
const api = process.env.E2E_API_URL || "http://localhost:18080";
test("login, exact dates, transaction edit/filter, budget, recurring, password and logout", async ({page, request}) => {
  const email = `e2e-${Date.now()}@example.com`;
  const password = "test-password-123";
  expect((await request.post(`${api}/api/auth/register`, {data: {email, password, fullName: "E2E User"}})).ok()).toBeTruthy();
  const login = await request.post(`${api}/api/auth/login`, {data: {email, password}});
  const token = (await login.json()).accessToken;
  const response = await request.post(`${api}/api/categories`, {headers: {Authorization: `Bearer ${token}`}, data: {name: "E2E Food", type: "EXPENSE"}});
  const category = await response.json();
  await page.goto("/login");
  await page.getByLabel("Email").fill(email); await page.getByLabel("Password", {exact:true}).fill(password);
  await page.getByRole("button", {name: "Sign in", exact:true}).click(); await expect(page).toHaveURL(/dashboard/);
  await page.goto("/transactions");
  await page.getByPlaceholder("Amount", {exact:true}).fill("12.34");
  await page.locator("form select").nth(1).selectOption(String(category.id));
  await page.locator('form input[type="date"]').fill("2024-02-29");
  await page.getByPlaceholder("Description", {exact:true}).fill("Leap lunch");
  await page.getByRole("button", {name:"Create",exact:true}).click();
  await expect(page.getByText("Transaction created.")).toBeVisible();
  await page.getByRole("button", {name:"Edit",exact:true}).click();
  await expect(page.locator('form input[type="date"]')).toHaveValue("2024-02-29");
  await page.getByPlaceholder("Amount", {exact:true}).fill("15.25");
  await page.getByRole("button", {name:"Update",exact:true}).click();
  await expect(page.getByText("Transaction updated.")).toBeVisible();
  await page.locator('input[type="date"]').nth(1).fill("2024-02-29");
  await page.locator('input[type="date"]').nth(2).fill("2024-02-29");
  await page.getByRole("button", {name:"Filter",exact:true}).click();
  await expect(page.getByRole("cell", {name:"15 ₫",exact:true})).toBeVisible();
  await page.goto("/budgets");
  await page.getByLabel("Quick month").fill("2024-02");
  await expect(page.locator('form input[type="date"]').nth(1)).toHaveValue("2024-02-29");
  await page.locator("form select").selectOption(String(category.id));
  await page.getByPlaceholder("Amount", {exact:true}).fill("100.00");
  await page.getByRole("button", {name:"Create budget",exact:true}).click();
  await expect(page.getByRole("button", {name:"Edit",exact:true})).toBeVisible();
  await page.goto("/recurring-transactions");
  await page.getByPlaceholder("Amount", {exact:true}).fill("20.00");
  await page.locator("form select").nth(1).selectOption(String(category.id));
  await page.locator('form input[type="date"]').first().fill("2024-02-29");
  await page.getByRole("button", {name:"Create schedule",exact:true}).click();
  await expect(page.getByRole("button", {name:"Generate",exact:true})).toBeVisible();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", {name:"Generate",exact:true}).click();
  await expect(page.getByText(/Generated transaction/)).toBeVisible();
  await page.goto("/account");
  await page.getByPlaceholder("Current password", {exact:true}).fill("wrong-password");
  await page.getByPlaceholder("New password", {exact:true}).fill("new-password-123");
  await page.getByPlaceholder("Confirm new password", {exact:true}).fill("new-password-123");
  await page.getByRole("button", {name:"Change password",exact:true}).click();
  await expect(page.getByText("Current password is incorrect")).toBeVisible();
  await expect(page).toHaveURL(/account/);
  await page.getByPlaceholder("Current password", {exact:true}).fill(password);
  await page.getByRole("button", {name:"Change password",exact:true}).click();
  await expect(page.getByText("Password changed successfully.")).toBeVisible();
  await page.getByRole("button", {name:"Sign out",exact:true}).click(); await expect(page).toHaveURL(/login/);
  expect(await page.evaluate(() => localStorage.getItem("accessToken"))).toBeNull();
  expect(await page.evaluate(() => localStorage.getItem("user"))).toBeNull();
});
test("invalid session redirects away from protected UI", async ({page}) => {
  await page.goto("/login");
  await page.evaluate(() => { localStorage.setItem("accessToken", "malformed-jwt"); localStorage.setItem("user", JSON.stringify({email:"stale@example.com"})); });
  await page.goto("/dashboard"); await expect(page).toHaveURL(/login/);
  expect(await page.evaluate(() => localStorage.getItem("user"))).toBeNull();
});
