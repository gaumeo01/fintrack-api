-- Empty database baseline. Existing installations explicitly baseline at version 1.
CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(150) NOT NULL UNIQUE, password_hash varchar(255) NOT NULL,
 full_name varchar(100) NOT NULL, role varchar(255) NOT NULL,
 created_at timestamp NOT NULL, updated_at timestamp NOT NULL
);
CREATE TABLE categories (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(100) NOT NULL, type varchar(255) NOT NULL,
 user_id bigint NOT NULL REFERENCES users(id), created_at timestamp NOT NULL, updated_at timestamp NOT NULL
);
CREATE TABLE accounts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(100) NOT NULL, type varchar(255) NOT NULL,
 initial_balance numeric(19,2) NOT NULL, current_balance numeric(19,2) NOT NULL,
 active boolean NOT NULL, user_id bigint NOT NULL REFERENCES users(id),
 created_at timestamp NOT NULL, updated_at timestamp NOT NULL
);
CREATE TABLE budgets (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), category_id bigint NOT NULL REFERENCES categories(id),
 amount numeric(19,2) NOT NULL, start_date date NOT NULL, end_date date NOT NULL,
 created_at timestamp NOT NULL, updated_at timestamp NOT NULL
);
CREATE TABLE recurring_transactions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), category_id bigint NOT NULL REFERENCES categories(id),
 type varchar(255) NOT NULL, amount numeric(19,2) NOT NULL, description varchar(255),
 frequency varchar(255) NOT NULL, start_date date NOT NULL, end_date date,
 next_run_date date NOT NULL, active boolean NOT NULL,
 created_at timestamp NOT NULL, updated_at timestamp NOT NULL
);
CREATE TABLE transactions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), category_id bigint NOT NULL REFERENCES categories(id),
 type varchar(255) NOT NULL, amount numeric(19,2) NOT NULL, description varchar(255),
 transaction_date date NOT NULL, created_at timestamp NOT NULL, updated_at timestamp NOT NULL
);
